"""전략서 v0.2 Pydantic 모델 + JSON Schema export (docs/strategy-spec-v0.2.md).

전략서는 규칙 코드가 조립한다 (LLM 은 빈칸만 채운다). 그래서 탈출구 값(UNKNOWN 등)이나
판정(verdict)·질문 칸이 전략서에 없다. 그건 빈칸 단계의 일이다.

형식
- 비교 하나:  {"left": 지표, "op": 연산자, "right": 지표 | {"value": 숫자}}
- 지표:       {"indicator": 이름, "window": 기간(없으면 생략), "of": "self" | "KOSPI200" | "KOSDAQ" | "VIX" | 종목코드}
- 묶음:       {"all": [조건...]} / {"any": [조건...]} (중첩 가능)
- rules:      {"target": "each", "entry": 조건 | null, "exit": 조건 | null}. null 이면 배분만 하는 전략
- assets:     [{"ticker", "name", "weight": 0~1 | null}]. weight 가 모두 null 이면 1/N 자리
- max_weight: 종목당 최대 비중 (사용자 제한, 0~1)
- rebalance:  monthly_first | monthly_mid | quarterly | weekly | drift_5pp | null

여기서는 모양(타입·허용값·0~1 범위)만 본다. 기간이 허용 목록에 있는지, of 가 그 지표에 맞는지,
단위가 맞는지 같은 건 core.validate 2·3단계가 한국어 메시지로 잡는다.

내보내기: python -m core.schema   → schema/strategy-v0.2.json
"""
from __future__ import annotations

import json
from datetime import date
from pathlib import Path
from typing import Literal, Optional, Union

from pydantic import BaseModel, ConfigDict, Field, field_validator

from core.dictionary import INDICATORS, OPERATORS, REBALANCE

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_PATH = ROOT / "schema" / "strategy-v0.2.json"
SCHEMA_VERSION = "0.2"

IndicatorName = Literal[tuple(INDICATORS)]   # type: ignore[valid-type]
Op = Literal[tuple(OPERATORS)]               # type: ignore[valid-type]
RebalancePeriod = Literal[tuple(REBALANCE)]  # type: ignore[valid-type]


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=False)


class Operand(_Strict):
    indicator: IndicatorName
    window: Optional[int] = None
    of: str = Field("self", min_length=1)


class Value(_Strict):
    value: float


class Compare(_Strict):
    left: Operand
    op: Op
    right: Union[Operand, Value]


class AllOf(_Strict):
    all: list["Cond"] = Field(min_length=1)


class AnyOf(_Strict):
    any: list["Cond"] = Field(min_length=1)


Cond = Union[Compare, AllOf, AnyOf]
AllOf.model_rebuild()
AnyOf.model_rebuild()


class Rules(_Strict):
    target: Literal["each"] = "each"
    entry: Optional[Cond] = None
    exit: Optional[Cond] = None


class Asset(_Strict):
    ticker: str = Field(min_length=1)
    name: str
    weight: Optional[float] = Field(None, gt=0, le=1)    # None = 1/N 자리


class BacktestConfig(_Strict):
    start: str = Field("2023-01-01", pattern=r"^\d{4}-\d{2}-\d{2}$")
    end: str = Field("2025-12-31", pattern=r"^\d{4}-\d{2}-\d{2}$")
    initial_cash: float = Field(10_000_000, gt=0)
    commission_rate: float = Field(0.00015, ge=0, lt=0.1)   # 0.015% (매수·매도 각각)
    slippage_rate: float = Field(0.0005, ge=0, lt=0.1)      # 0.05% (매수는 비싸게, 매도는 싸게)

    @field_validator("start", "end")
    @classmethod
    def _real_date(cls, v: str) -> str:
        date.fromisoformat(v)  # 2025-02-30 같은 값은 ValueError
        return v


class Strategy(_Strict):
    schema_version: Literal["0.2"] = SCHEMA_VERSION
    assets: list[Asset] = Field(min_length=1)
    max_weight: Optional[float] = Field(None, gt=0, le=1)
    rebalance: Optional[RebalancePeriod] = None
    rules: Optional[Rules] = None
    backtest: BacktestConfig = Field(default_factory=BacktestConfig)
    # 기본값으로 채운 빈칸 (화면에 "기본값 사용" 표시용). 실행에는 영향이 없어 해시에서 뺀다.
    defaults_applied: list[str] = Field(default_factory=list)


def iter_compares(cond: Optional[Cond], path: str):
    """조건 트리의 비교를 (경로, Compare) 로 순회. 경로 예: 'rules.entry.all[1].any[0]'."""
    if cond is None:
        return
    if isinstance(cond, Compare):
        yield path, cond
    elif isinstance(cond, AllOf):
        for i, c in enumerate(cond.all):
            yield from iter_compares(c, f"{path}.all[{i}]")
    else:
        for i, c in enumerate(cond.any):
            yield from iter_compares(c, f"{path}.any[{i}]")


# ---------------------------------------------------------------- JSON Schema export

def build_json_schema() -> dict:
    schema = Strategy.model_json_schema()
    schema["$comment"] = ("generated by `python -m core.schema` — 직접 수정 금지. "
                          "지표·연산자·리밸런싱 주기는 전략 요소 사전(core/dictionary.py) 값만 허용.")
    return schema


def dump_json_schema(schema: dict) -> str:
    return json.dumps(schema, ensure_ascii=False, indent=2) + "\n"


def export_json_schema(path: Path | str = SCHEMA_PATH) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump_json_schema(build_json_schema()), encoding="utf-8", newline="\n")
    return path


if __name__ == "__main__":
    print(f"wrote {export_json_schema()}")
